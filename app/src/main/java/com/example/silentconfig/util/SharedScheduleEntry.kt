package com.example.aquiethours.util

import android.util.Base64
import com.example.aquiethours.data.Schedule
import com.google.gson.Gson
import com.google.gson.reflect.TypeToken
import java.io.ByteArrayOutputStream
import java.time.DayOfWeek
import java.util.zip.Deflater
import java.util.zip.Inflater

data class SharedScheduleEntry(
    val day: DayOfWeek,
    val startHour: Int,
    val startMinute: Int,
    val endHour: Int,
    val endMinute: Int,
    val label: String
)

object ShareHelper {
    private val gson = Gson()

    fun encodeSchedules(schedules: List<Schedule>): String {
        val sb = StringBuilder()
        for (i in schedules.indices) {
            val s = schedules[i]
            val label = s.label.replace("|", "").replace(";", "")
            sb.append("${s.dayOfWeek.value};${s.startHour};${s.startMinute};${s.endHour};${s.endMinute};$label")
            if (i < schedules.size - 1) sb.append("|")
        }

        val bytes = sb.toString().toByteArray(Charsets.UTF_8)
        val deflater = Deflater(Deflater.BEST_COMPRESSION)
        deflater.setInput(bytes)
        deflater.finish()
        val out = ByteArrayOutputStream()
        val buffer = ByteArray(1024)
        while (!deflater.finished()) {
            val count = deflater.deflate(buffer)
            out.write(buffer, 0, count)
        }
        deflater.end()

        val encoded = Base64.encodeToString(out.toByteArray(), Base64.NO_WRAP or Base64.URL_SAFE)
        return "v2:$encoded"
    }

    /**
     * Decodes a share code / AI output and drops anything that would later blow up
     * the scheduler: out-of-range hours/minutes (LocalTime.of throws, crashing the
     * app inside AlarmScheduler) and zero-length entries (start == end silently
     * became a 24-hour schedule). Returns null if nothing usable is left.
     */
    fun decodeSchedules(encodedString: String): List<ParsedScheduleEntry>? {
        val raw = decodeRaw(encodedString.trim()) ?: return null
        val valid = raw.filter {
            it.startHour in 0..23 && it.endHour in 0..23 &&
                it.startMinute in 0..59 && it.endMinute in 0..59 &&
                (it.startHour * 60 + it.startMinute) != (it.endHour * 60 + it.endMinute)
        }
        return valid.ifEmpty { null }
    }

    private fun decodeRaw(encodedString: String): List<ParsedScheduleEntry>? {
        if (encodedString.startsWith("v2:")) {
            return try {
                val base64Str = encodedString.removePrefix("v2:")
                val bytes = Base64.decode(base64Str, Base64.NO_WRAP or Base64.URL_SAFE)
                val inflater = Inflater()
                inflater.setInput(bytes)
                val out = ByteArrayOutputStream()
                val buffer = ByteArray(1024)
                while (!inflater.finished()) {
                    val count = inflater.inflate(buffer)
                    // Truncated/corrupt input: inflate() returns 0 forever and this
                    // loop used to spin on the UI thread, freezing the app.
                    if (count == 0 && (inflater.needsInput() || inflater.needsDictionary())) {
                        inflater.end()
                        return null
                    }
                    out.write(buffer, 0, count)
                }
                inflater.end()
                val decodedStr = String(out.toByteArray(), Charsets.UTF_8)
                parseDelimitedString(decodedStr)
            } catch (e: Exception) {
                e.printStackTrace()
                null
            }
        } else if (encodedString.contains(";")) {
            // A single-class timetable from the AI has no "|" separator; requiring one
            // sent it down the Base64 path below and the import always "failed".
            // Support raw delimited string generated by AI
            return try {
                parseDelimitedString(encodedString.trim())
            } catch (e: Exception) {
                e.printStackTrace()
                null
            }
        } else {
            // Fallback to old format
            return try {
                val json = String(Base64.decode(encodedString, Base64.NO_WRAP))
                val type = object : TypeToken<List<SharedScheduleEntry>>() {}.type
                val entries: List<SharedScheduleEntry> = gson.fromJson(json, type)
                
                entries.map {
                    ParsedScheduleEntry(
                        day = it.day,
                        startHour = it.startHour,
                        startMinute = it.startMinute,
                        endHour = it.endHour,
                        endMinute = it.endMinute,
                        label = it.label
                    )
                }
            } catch (e: Exception) {
                e.printStackTrace()
                null
            }
        }
    }

    private fun parseDelimitedString(decodedStr: String): List<ParsedScheduleEntry> {
        // AI output is messy: newlines instead of "|", spaces around numbers, a missing
        // label. One bad record used to throw and fail the whole import; now it's skipped.
        return decodedStr
            .split('|', '\n')
            .map { it.trim() }
            .filter { it.isNotEmpty() }
            .mapNotNull { record ->
                val parts = record.split(";", limit = 6).map { it.trim() }
                if (parts.size < 5) return@mapNotNull null
                val nums = parts.take(5).map { it.toIntOrNull() ?: return@mapNotNull null }
                if (nums[0] !in 1..7) return@mapNotNull null
                ParsedScheduleEntry(
                    day = DayOfWeek.of(nums[0]),
                    startHour = nums[1],
                    startMinute = nums[2],
                    endHour = nums[3],
                    endMinute = nums[4],
                    label = parts.getOrElse(5) { "" }
                )
            }
    }
}
